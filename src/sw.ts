import { defaultCache } from "@serwist/vite/worker";
import type { PrecacheEntry, SerwistGlobalConfig } from "serwist";
import { Serwist, NetworkFirst } from "serwist";

// This declares the value of `injectionPoint` to TypeScript.
// `injectionPoint` is the string that will be replaced by the
// actual precache manifest. By default, this string is set to
// `"self.__SW_MANIFEST"`.
declare global {
  interface WorkerGlobalScope extends SerwistGlobalConfig {
    __SW_MANIFEST: (PrecacheEntry | string)[] | undefined;
  }
}

declare const self: ServiceWorkerGlobalScope;

const pagesStrategy = new NetworkFirst({
  cacheName: "pages",
  networkTimeoutSeconds: 3,
});

const serwist = new Serwist({
  precacheEntries: self.__SW_MANIFEST,
  skipWaiting: true,
  clientsClaim: true,
  navigationPreload: true,
  runtimeCaching: [
    {
      matcher: ({ request }) => request.mode === "navigate",
      handler: pagesStrategy,
    },
    ...defaultCache,
  ],
  fallbacks: {
    entries: [
      {
        matcher: ({ request }) => request.mode === "navigate",
        url: "/",
      },
    ],
  },
});

// On install, cache core routes with pagesStrategy so they are available
// offline. Did this instad of precaching since they're generated by SSR.
const coreRoutes = ["/", "/faq", "/updates"];
self.addEventListener("install", (event) => {
  const warmPromises = coreRoutes.map((route) =>
    pagesStrategy.handle({
      request: new Request(route),
      event,
    }),
  );

  event.waitUntil(Promise.all(warmPromises));
});

serwist.addEventListeners();
